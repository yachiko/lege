#!/usr/bin/env python3
"""Generate the Homebrew cask for a lege release.

    python3 scripts/homebrew_cask.py VERSION CHECKSUMS > Casks/lege.rb

VERSION is the release version without the leading "v" (e.g. 0.1.0).
CHECKSUMS is the release's checksums.txt (`sha256sum` output for the
lege_VERSION_OS_ARCH.tar.gz archives).

The cask matches the ones GoReleaser writes for the other yachiko tools in
yachiko/homebrew-tap: per-platform archives, a `binary` stanza, and a
postflight step that strips macOS quarantine so the unsigned binary can run.
Standard library only.
"""

import sys

PLATFORMS = {
    # (brew block, CPU block): archive suffix
    ("on_macos", "on_arm"): "darwin_arm64",
    ("on_macos", "on_intel"): "darwin_amd64",
    ("on_linux", "on_arm"): "linux_arm64",
    ("on_linux", "on_intel"): "linux_amd64",
}

TEMPLATE = """\
# This file is generated by lege's release workflow. DO NOT EDIT.
cask "lege" do
  version "{version}"

{platforms}
  name "lege"
  desc "Minimal Markdown viewer and explorer"
  homepage "https://github.com/yachiko/lege"

  livecheck do
    skip "Auto-generated on release."
  end

  binary "lege"

  postflight_steps do
    on_macos do
      run "/usr/bin/xattr",
          args: ["-dr", "com.apple.quarantine", "{{{{staged_path}}}}/lege"]
    end
  end

  caveats <<~EOS
    On Linux, lege renders through WebKitGTK 4.1 from your distribution:
      Debian/Ubuntu: sudo apt install libwebkit2gtk-4.1-0
      Fedora:        sudo dnf install webkit2gtk4.1
      Arch:          sudo pacman -S webkit2gtk-4.1
  EOS

  # No zap stanza required
end
"""


def read_checksums(path):
    sums = {}
    with open(path) as f:
        for line in f:
            if line.strip():
                digest, name = line.split()
                sums[name.lstrip("*")] = digest
    return sums


def platform_blocks(version, sums):
    lines = []
    for os_block in ("on_macos", "on_linux"):
        lines.append(f"  {os_block} do")
        for cpu_block in ("on_arm", "on_intel"):
            archive = f"lege_{version}_{PLATFORMS[(os_block, cpu_block)]}.tar.gz"
            if archive not in sums:
                sys.exit(f"homebrew_cask: {archive} is missing from the checksums")
            lines += [
                f"    {cpu_block} do",
                f'      sha256 "{sums[archive]}"',
                f'      url "https://github.com/yachiko/lege/releases/download/v#{{version}}/lege_#{{version}}_{PLATFORMS[(os_block, cpu_block)]}.tar.gz"',
                "    end",
            ]
        lines.append("  end")
    return "\n".join(lines) + "\n"


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__.strip().splitlines()[2].strip())
    version, checksums = sys.argv[1].removeprefix("v"), sys.argv[2]
    sums = read_checksums(checksums)
    sys.stdout.write(TEMPLATE.format(version=version, platforms=platform_blocks(version, sums)))


if __name__ == "__main__":
    main()
